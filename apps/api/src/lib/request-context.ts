/**
 * زمینهٔ درخواست — تا `ip` و `device` به لاگ حسابرسی برسند.
 *
 * ── چه چیزی خراب بود ──────────────────────────────────────────────
 *
 * `platform.audit_log` دو ستون `ip` و `device` دارد و
 * `platform.set_actor(uuid, inet, text)` هم هر دو را می‌گیرد. ولی
 * **تقریباً هیچ عملیات مالی‌ای پرشان نمی‌کرد.** اندازه‌گیری، نه فرض:
 *
 *     action        n    ip NULL   device NULL
 *     session.open  21      0           0      ← فقط این
 *     shift.open     1      1           1
 *
 * علتش دو تعریف از یک مفهوم بود:
 *
 *     lib/idempotency.ts  setActor(trx, userId, ip?, device?)   ← پرکاربرد
 *     db/actor.ts         setActor(trx, { userId, ip?, device? })
 *
 * نسخهٔ اول راحت‌تر است و **~۷۰ فراخوان** در همهٔ ماژول‌های مالی فقط دو
 * آرگومان اول را می‌دهند: فاکتور، مرجوعی، رسید خرید، انتقال،
 * انبارگردانی، چک، خزانه، مشتری، کالا. پس معیار پذیرش ۱۳ سند («هر
 * عملیات حساس کاربر، زمان و **دستگاه** ثبت‌کننده را نشان دهد») برقرار
 * نبود.
 *
 * ── چرا این راه، و نه پاس‌دادن به ۷۰ فراخوان ───────────────────────
 *
 * `ip` و `device` خصوصیتِ **درخواست**اند، نه پارامترِ منطق کسب‌وکار.
 * ریختنشان در امضای هر متد سرویس، ۷۰ جا را عوض می‌کند و هر متد تازه‌ای
 * که فردا نوشته شود باز هم می‌تواند فراموششان کند — یعنی همان کلاس باگ
 * برمی‌گردد.
 *
 * `AsyncLocalStorage` زمینه را به کل زنجیرهٔ `await` همان درخواست
 * می‌چسباند، پس `setActor` می‌تواند خودش برشان دارد. نتیجه: ۷۰ فراخوان
 * دست‌نخورده می‌مانند و **همه** درست می‌شوند.
 *
 * ⚠️ بیرون از یک درخواست HTTP — Worker، CLI، مهاجرت داده — زمینه‌ای
 *    نیست و هر دو `NULL` می‌مانند. این **درست** است: آن‌جا آدمی پشت یک
 *    مرورگر نیست و ساختن یک IP جعلی بدتر از نداشتنش است.
 */
import { AsyncLocalStorage } from "node:async_hooks";

export interface RequestContext {
  /** IP واقعی درخواست. */
  ip?: string | undefined;
  /** شناسه دستگاهِ نشست — از `identity.device`، نه یک رشتهٔ دلخواه. */
  device?: string | undefined;
}

const storage = new AsyncLocalStorage<RequestContext>();

/**
 * درخواست را **داخل** یک زمینه اجرا می‌کند.
 *
 * ⚠️ `enterWith` استفاده **نمی‌شود** و این یک درس از همین ممیزی است:
 *    نسخهٔ اول `enterWith` می‌زد و دو مشکل داشت، هر دو اندازه‌گیری‌شده:
 *
 *    ۱. پس از یک `await` اثر نمی‌گذاشت — `ip` می‌نشست و `device` که بعد
 *       از حل نشست ست می‌شد، نه.
 *    ۲. زمینه **بیرون از درخواست نشت می‌کرد**: یک عملیات خارج از HTTP در
 *       همان فرایند، IP درخواست قبلی را برمی‌داشت. دقیقاً همان کلاس
 *       اشکالی که `platform.set_actor` با `is_local = true` از آن
 *       پرهیز می‌کند — «در Pool اشتراکی به درخواست بعدی نشت نکن».
 *
 *    Hook به‌شکل **Callback** ثبت می‌شود و `done` داخل `run` صدا زده
 *    می‌شود، پس بقیهٔ چرخهٔ عمر درخواست داخل همان زمینه اجرا می‌شود و
 *    با پایانش تمام می‌شود.
 */
export function runInRequestContext(ctx: RequestContext, done: () => void): void {
  storage.run(ctx, done);
}

/**
 * زمینهٔ جاری، یا `{}` اگر بیرون از درخواست باشیم.
 *
 * شیء برگشتی **همان** شیء ذخیره‌شده است، پس می‌شود میدانی را که بعداً
 * معلوم می‌شود (مثل شناسهٔ دستگاه، پس از حل نشست) روی آن نوشت.
 */
export function currentRequestContext(): RequestContext {
  return storage.getStore() ?? {};
}

/** برای تست: اجرای یک تابع با زمینهٔ مشخص. */
export function withRequestContext<T>(ctx: RequestContext, fn: () => T): T {
  return storage.run(ctx, fn);
}
