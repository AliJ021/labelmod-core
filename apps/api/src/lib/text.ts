/**
 * نویسه‌های ممنوع در متنی که کاربر می‌نویسد — **یک تعریف، نه چهار تا**.
 *
 * ── چرا این فایل ساخته شد ──────────────────────────────────────────
 *
 * همین الگو عیناً در چهار پرونده مسیر کپی شده بود: کالا، محصول، خرید
 * و خزانه. قاعده خودِ این مخزن می‌گوید «دروازه یک تعریف دارد، نه دو
 * تا — کپی کردنش یعنی یکی‌شان عقب بماند، و همان است که دور زده
 * می‌شود». یک فیلتر امنیتی با چهار نسخه، چهار برابر شانس عقب‌ماندن
 * دارد.
 *
 * ── چه چیزی رد می‌شود، و چرا ───────────────────────────────────────
 *
 * دو دسته، هر دو با پیامد دیدنی:
 *
 *   • **کنترلی‌های C0/C1 و DEL** — در برچسب چاپی و در جدول دیده
 *     نمی‌شوند ولی خروجی را خراب می‌کنند.
 *
 *   • **نشانه‌های جهت‌دهی دوطرفه** (LRM/RLM/LRE…/RLO و ایزوله‌ها) —
 *     می‌توانند ظاهر متن را **وارونه** نشان دهند بدون اینکه محتوا عوض
 *     شود. روی برچسب قیمت یعنی عددی که چشم می‌خواند با عددی که ذخیره
 *     شده یکی نباشد. در یک فروشگاه این یک راه تقلب است، نه یک ایراد
 *     نمایشی.
 *
 * ⚠️ صریح با **کد نویسه** نوشته شده، نه با خودِ نویسه: نویسه کنترلیِ
 *    خام در سورس نامرئی است و فایل را از نظر ابزارها دودویی می‌کند —
 *    همان اتفاقی که یک بار در این مخزن افتاد و ۳۴ مسیر خرید را ماه‌ها
 *    بدون Diff از بازبینی رد کرد.
 */

// eslint-disable-next-line no-control-regex -- گرفتنِ همین نویسه‌ها تمام هدف این الگوست
export const CONTROL_CHARS = /[\u0000-\u001f\u007f-\u009f\u200e\u200f\u202a-\u202e\u2066-\u2069]/;

/** پیام یکسان، تا کاربر در هر صفحه یک جمله ببیند. */
export const CONTROL_CHARS_MESSAGE = "شامل نویسه کنترلی است";

/** آیا این متن نویسه ممنوع دارد؟ */
export function hasControlChars(value: string): boolean {
  return CONTROL_CHARS.test(value);
}
