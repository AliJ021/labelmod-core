/**
 * کدام کشو؟ — تنها تعریف.
 *
 * ── چرا این پرونده هست ──────────────────────────────────────────────
 *
 * هر ریالی که از کشوی صندوق خارج یا وارد می‌شود باید به یک **شیفت باز**
 * بچسبد، وگرنه شمارش پایان شیفت مغایرت کاذب می‌دهد. دیتابیس نمی‌تواند
 * این را اجبار کند — نمی‌داند کدام کاربر کدام کشو را باز دارد — پس
 * دروازه‌اش در لایه HTTP است.
 *
 * ⚠️ **شیفت از «شعبه» گرفته می‌شود، نه از کاربر عامل.** پولی که از کشو
 *    خارج می‌شود لزوماً به دست صاحب همان کشو خارج نمی‌شود:
 *
 *      • مدیر برای کرایه پیک از کشوی صندوق‌دار برمی‌دارد و خودش
 *        شیفتی ندارد.
 *      • بازپرداخت نقدی مرجوعی `refund.cash` می‌خواهد و **صندوق‌دار
 *        آن را ندارد** — سرپرست بازپرداخت را می‌زند، ولی پول از کشوی
 *        صندوق‌دار بیرون می‌آید.
 *
 * ── و چرا یک تعریف، نه دو تا ────────────────────────────────────────
 *
 * این منطق اول فقط در `treasury-routes.ts` بود و `return-routes.ts`
 * نسخه خودش را داشت که **شیفت خودِ کاربر** را می‌خواست
 * (`shifts.current(userId, branch)`). نتیجه‌اش اندازه‌گیری شد، نه حدس:
 *
 *      صندوق‌دار (صاحب کشو) بازپرداخت نقدی   → ۴۰۳ deny
 *      سرپرست  (مجوزدار، بی‌کشو)            → ۴۲۲ no_open_shift
 *
 * یعنی در یک روز عادی با یک کشو، **هیچ‌کس** نمی‌توانست بازپرداخت نقدی
 * بزند. و راه دور زدنش (سرپرست کشوی دومی باز کند) بدتر بود:
 *
 *      کشوی صندوق‌دار: انتظار ۱۲٬۰۰۰٬۰۰۰ ، شمارش ۱۱٬۰۰۰٬۰۰۰ → −۱٬۰۰۰٬۰۰۰
 *      کشوی سرپرست  : انتظار −۱٬۰۰۰٬۰۰۰ (کشوی منفی!)        → +۱٬۰۰۰٬۰۰۰
 *
 * دو مغایرت کاذب و یک «کشوی منفی» — دقیقاً همان چیزی که این دروازه
 * برای جلوگیری از آن نوشته شده بود.
 *
 * ── قرارداد ─────────────────────────────────────────────────────────
 *
 * این تابع **خطا پرتاب نمی‌کند**: نتیجه را برمی‌گرداند و هر مسیر آن را
 * به کلاس خطای خودش ترجمه می‌کند (`TreasuryError` / `ReturnError`). پس
 * تصمیم یک جا است و شکل پاسخ هر مسیر دست خودش می‌ماند.
 */
import type { ShiftService } from "../sales/shift.ts";

export type DrawerOutcome =
  | { ok: true; shiftId: string }
  | { ok: false; code: DrawerRefusal; message: string; status: 422 };

export type DrawerRefusal = "wrong_shift" | "no_open_shift" | "ambiguous_shift";

/**
 * کشوی باز این **شعبه** را پیدا می‌کند.
 *
 * @param given شیفتی که کلاینت صریح فرستاده — اگر بیاید، فقط اعتبارش
 *              سنجیده می‌شود. حدس‌زدن جای کلاینت یعنی مغایرت را از یک
 *              صندوق‌دار به دیگری منتقل کنیم.
 */
export async function resolveCashDrawer(
  shifts: ShiftService,
  branchId: string,
  given: string | undefined,
): Promise<DrawerOutcome> {
  const open = await shifts.openInBranch(branchId);

  if (given !== undefined) {
    if (!open.some((x) => x.id === given)) {
      return {
        ok: false,
        code: "wrong_shift",
        message: "شیفت فرستاده‌شده در این شعبه باز نیست.",
        status: 422,
      };
    }
    return { ok: true, shiftId: given };
  }

  if (open.length === 0) {
    // بدون شیفت باز، کشویی هم باز نیست. این یک خطاست، نه اجازه: پولی
    // که ادعا می‌شود از کشو رفته ولی کشو بسته بوده، یا اشتباه است یا
    // باید به حساب دیگری بخورد.
    return {
      ok: false,
      code: "no_open_shift",
      message: "برای جابه‌جایی پول نقد، شیفت صندوق باید باز باشد.",
      status: 422,
    };
  }

  if (open.length > 1) {
    // دو کشوی باز یعنی نمی‌شود حدس زد پول از کدام رفته.
    return {
      ok: false,
      code: "ambiguous_shift",
      message: `${open.length} شیفت در این شعبه باز است؛ مشخص کنید پول از کدام کشو رفته.`,
      status: 422,
    };
  }

  return { ok: true, shiftId: open[0]!.id };
}
