/**
 * کارمزد پایانه — سنجش‌های کوچکی که نباید در JSX بمانند.
 *
 * ── چرا رشته و نه عدد ────────────────────────────────────────────────
 *
 * `fee_percent` در دیتابیس `numeric(5,3)` است و در JSON **رشته**
 * می‌آید، به همان دلیلی که پول رشته می‌آید. نوشتن `Number(fee) === 0`
 * وسوسه‌انگیز است و اینجا حتی «کار می‌کند» — ولی همان الگویی است که
 * قاعده «پول هرگز از میان `Number()` رد نمی‌شود» بسته، و کپی‌شدنش به
 * جایی که مبلغ واقعی است فقط یک بار لازم دارد.
 */

/**
 * آیا این پایانه کارمزدی ندارد؟
 *
 * پرسشی که این تابع جواب می‌دهد **«آیا قرارداد PSP وارد شده؟»** است،
 * نه «آیا این رشته عدد صفر است؟». دو حالت یک جواب دارند:
 *
 *   ۰٫۰۰۰ و هم‌خانواده‌هایش  → عددی هست و صفر است
 *   رشته بی‌رقم («»، « »)   → عددی وارد نشده
 *
 * هر دو یعنی هیچ کارمزدی در سند ضرب نمی‌شود، و اثرشان یکی است: دفتر
 * کل مبلغ فاکتور را درآمد می‌بیند و بانک کمتر واریز می‌کند.
 *
 * ⚠️ جهت خطا عمدی است. هشدار اضافه فقط شلوغی است؛ هشدارِ نیامده یعنی
 * مغایرت بی‌صدا روی **هر تراکنش کارتی**. پس رشته‌ای که نمی‌شود از آن
 * یک کارمزد خواند، هشدار می‌گیرد — نه سکوت.
 *
 * `numeric(5,3)` یک مقدار را چند شکل برمی‌گرداند: «0»، «0.000»،
 * «.000». همه یک معنا دارند.
 */
export function isZeroFee(feePercent: string): boolean {
  const v = feePercent.trim();
  // هیچ رقمی ندارد — پس کارمزدی وارد نشده است.
  if (!/\d/.test(v)) return true;
  // رقم دارد و همه‌شان صفرند.
  return /^0*(\.0*)?$/.test(v);
}
