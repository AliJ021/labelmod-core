/**
 * «این پایانه کارمزدی ندارد» — و چرا یک تست دارد.
 *
 * نبودِ کارمزد یک هشدار روی صفحه تنظیمات روشن می‌کند، چون تا امضای
 * قرارداد PSP همان صفرِ Seed آنجا نشسته و اثرش بی‌صداست: دفتر کل مبلغ
 * فاکتور را درآمد می‌بیند، بانک کمتر واریز می‌کند، و تفاوت جایی ثبت
 * نمی‌شود. هشداری که اشتباه خاموش بماند، بدتر از نبودنش است.
 *
 * `fee_percent` از `numeric(5,3)` می‌آید و **رشته** است، نه عدد. پس
 * یک مقدار، چند شکل دارد: «0»، «0.000»، «.000».
 *
 * ── جهت خطا عمدی است ─────────────────────────────────────────────────
 *
 * پرسش این تابع «آیا این رشته عدد صفر است؟» نیست؛ «آیا قرارداد PSP
 * وارد شده؟» است. رشته‌ای که هیچ رقمی ندارد همان‌قدر جواب «نه»
 * می‌دهد که ۰٫۰۰۰ می‌دهد — و در هر دو حالت هیچ کارمزدی در سند ضرب
 * نمی‌شود.
 *
 * پس هشدار می‌گیرد، نه سکوت: هشدار اضافه شلوغی است، هشدارِ نیامده
 * مغایرت بی‌صدا روی **هر تراکنش کارتی**.
 *
 * مهم‌ترین ادعا وسطی است: **۰٫۰۰۱ صفر نیست.** کارمزدی که واقعاً وارد
 * شده نباید هشدارِ «وارد نشده» بگیرد، وگرنه کاربر یاد می‌گیرد هشدار
 * را نادیده بگیرد — و آن‌وقت هشدارِ واقعی هم دیده نمی‌شود.
 */
import { describe, test } from "node:test";
import assert from "node:assert/strict";
import { isZeroFee } from "../src/lib/settlement.ts";

describe("پایانه بدون کارمزد", () => {
  test("همه شکل‌های صفر که numeric(5,3) برمی‌گرداند، صفر شمرده می‌شوند", () => {
    for (const v of ["0", "0.0", "0.00", "0.000", ".000", "00.000", " 0.000 "]) {
      assert.equal(isZeroFee(v), true, `«${v}» باید صفر شمرده شود`);
    }
  });

  test("کارمزد واقعی صفر شمرده نمی‌شود — حتی کوچک‌ترینش", () => {
    // ۰٫۰۰۱ کوچک‌ترین مقدار غیرصفری است که `numeric(5,3)` می‌تواند
    // نگه دارد. اگر این صفر شمرده شود، هشدار روی پایانه‌ای روشن
    // می‌ماند که قراردادش وارد شده.
    for (const v of ["0.001", "0.5", "1", "1.250", "2.900", "10.000"]) {
      assert.equal(isZeroFee(v), false, `«${v}» نباید صفر شمرده شود`);
    }
  });

  test("رشته بی‌رقم هم کارمزد ندارد — پس هشدار می‌گیرد، نه سکوت", () => {
    // فاصله خالی یعنی عددی وارد نشده. سکوت اینجا یعنی پایانه‌ای که
    // قراردادش وارد نشده هیچ هشداری نگیرد — همان مغایرت بی‌صدا.
    for (const v of ["", "   ", "\t", ".", "-"]) {
      assert.equal(isZeroFee(v), true, `«${v}» کارمزدی ندارد`);
    }
  });
});
