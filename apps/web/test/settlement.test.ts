/**
 * «کارمزد این پایانه صفر است» — و چرا یک تست دارد.
 *
 * صفر بودن کارمزد یک هشدار روی صفحه تنظیمات روشن می‌کند، چون تا امضای
 * قرارداد PSP همان صفرِ Seed آنجا نشسته و اثرش بی‌صداست: دفتر کل مبلغ
 * فاکتور را درآمد می‌بیند، بانک کمتر واریز می‌کند، و تفاوت جایی ثبت
 * نمی‌شود. هشداری که اشتباه خاموش بماند، بدتر از نبودنش است.
 *
 * `fee_percent` از `numeric(5,3)` می‌آید و **رشته** است، نه عدد. پس
 * یک مقدار، چند شکل دارد: «0»، «0.000»، «.000». اگر روزی کسی این را
 * با `Number(fee) === 0` بازنویسی کند تست سبز می‌ماند — ولی همان الگو
 * است که قاعده «پول هرگز از میان `Number()` رد نمی‌شود» بسته، و
 * کپی‌شدنش به جایی که مبلغ واقعی است فقط یک بار لازم دارد.
 *
 * مهم‌ترین ادعا آخری است: **۰٫۰۰۱ صفر نیست.** کارمزدی که واقعاً وارد
 * شده نباید هشدارِ «وارد نشده» بگیرد، وگرنه کاربر یاد می‌گیرد هشدار را
 * نادیده بگیرد.
 */
import { describe, test } from "node:test";
import assert from "node:assert/strict";
import { isZeroFee } from "../src/lib/settlement.ts";

describe("کارمزد صفر", () => {
  test("همه شکل‌های صفر که numeric(5,3) برمی‌گرداند، صفر شمرده می‌شوند", () => {
    for (const v of ["0", "0.0", "0.00", "0.000", ".000", "00.000", " 0.000 "]) {
      assert.equal(isZeroFee(v), true, `«${v}» باید صفر شمرده شود`);
    }
  });

  test("کارمزد واقعی صفر شمرده نمی‌شود — حتی کوچک‌ترینش", () => {
    // ۰٫۰۰۱ کوچک‌ترین مقدار غیرصفری است که `numeric(5,3)` می‌تواند
    // نگه دارد. اگر این صفر شمرده شود، هشدار روی پایانه‌ای روشن
    // می‌ماند که قراردادش وارد شده.
    for (const v of ["0.001", "0.5", "1", "1.250", "2.900", "10.000"]) {
      assert.equal(isZeroFee(v), false, `«${v}» نباید صفر شمرده شود`);
    }
  });

  test("رشته بی‌رقم صفر نیست — «نمی‌دانم» با «صفر» یکی نیست", () => {
    // پاسخ خالی یا خراب یعنی مقدار خوانده نشده. ادعای «کارمزد صفر
    // است» یک ادعای مثبت است و از هیچ ساخته نمی‌شود.
    for (const v of ["", "   ", ".", "-", "abc"]) {
      assert.equal(isZeroFee(v), false, `«${v}» یک کارمزد نیست`);
    }
  });
});
