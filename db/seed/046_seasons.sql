-- =====================================================================
-- فصل‌های کالا و انبار آوتلت — داده مرجع
-- =====================================================================
-- تفکیک گرم و سرد چیزی است که مالک برای چیدمان انبار می‌خواهد: کالای
-- فصل سرد در تابستان جای قفسه را می‌گیرد.
--
-- `all` برای کالای چهارفصل است — زیرپوش و جوراب نه گرم‌اند نه سرد، و
-- مجبورکردنشان به یکی از دو گروه یعنی گزارش «کالای فصل سرد» چیزی
-- نشان دهد که همیشه فروش دارد.
-- =====================================================================

INSERT INTO catalog.season (code, label, climate, sort_order) VALUES
  ('spring',      'بهار',          'warm', 10),
  ('summer',      'تابستان',       'warm', 20),
  ('autumn',      'پاییز',         'cold', 30),
  ('winter',      'زمستان',        'cold', 40),
  ('spring_summer','بهار و تابستان','warm', 50),
  ('autumn_winter','پاییز و زمستان','cold', 60),
  ('all_season',  'چهارفصل',       'all',  70)
ON CONFLICT (code) DO NOTHING;

-- انبار آوتلت شعبه اصلی. مثل بقیه انبارها، یک مکان است نه یک برچسب:
-- بردن کالا به آوتلت همان انتقال بین انبارهاست که از قبل ساخته شده و
-- ارزش را دقیقاً جابه‌جا می‌کند.
INSERT INTO inventory.warehouse (branch_id, code, name, kind)
SELECT b.id, 'OUTLET', 'آوتلت — تک‌سایز حراجی', 'outlet'
  FROM platform.branch b
 WHERE b.code = 'MAIN'
ON CONFLICT (code) DO NOTHING;
