#!/usr/bin/env bash
# =====================================================================
# تمرین بازیابی، وقتی بکاپی نیست، باید **حرف بزند**
# =====================================================================
# `ops/restore-drill.sh` پیامی برای «بکاپ پیدا نشد» داشت و آن پیام
# **هرگز چاپ نمی‌شد** اگر پوشهٔ بکاپ وجود نداشت:
#
#     set -euo pipefail  +  find <پوشهٔ ناموجود>  → کد ۱
#     pipefail آن را به کل لوله می‌برد
#     set -e اسکریپت را می‌کشد — پیش از رسیدن به پیام
#
# نتیجه: خروجی **صفر بایت**، کد ۱. یعنی یک cron شبانه هر شب شکست
# می‌خورد و هیچ‌کس یک کلمه نمی‌دید. دقیقاً همان کلاسی که این ممیزی سه
# بار پیدا کرد: نگهبانی که کار می‌کند ولی چیزی نمی‌گوید.
#
# ⚠️ پوشهٔ **موجود ولی خالی** این باگ را نشان نمی‌داد — آنجا `find`
#    موفق می‌شد و پیام چاپ. پس هر بازتولیدی باید پوشهٔ **ناموجود** را
#    هم بسنجد، وگرنه سبزِ بی‌معنا می‌گیرد.
#
# ⚠️ و بند ۴ **کنترل مثبت** است: با یک فایل `.dump` موجود، اسکریپت باید
#    از نگهبان **رد شود**. بی آن، یک نگهبانِ بیش از حد سخت‌گیر هم «پاس»
#    می‌شد و تمرین بازیابی را برای همیشه می‌شکست.
# =====================================================================
set -uo pipefail
export PGCLIENTENCODING="${PGCLIENTENCODING:-UTF8}"
: "${DATABASE_URL:?DATABASE_URL لازم است}"

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DRILL="$ROOT/ops/restore-drill.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
FAIL=0

# اجرا می‌کند و سه چیز را برمی‌گرداند: کد خروج، اندازهٔ خروجی، متن.
OUT=""; CODE=0
run_drill () {
  OUT="$(BACKUP_DIR="$1" "$DRILL" ${2:+"$2"} 2>&1)"; CODE=$?
}

# ادعا: باید شکست بخورد **و** حرف بزند **و** حرفش دربارهٔ بکاپ باشد.
expect_loud_failure () {
  local label="$1"
  if [ "$CODE" -eq 0 ]; then
    echo "  ✗ $label — موفق شد، در حالی که بکاپی نبود"; FAIL=1; return
  fi
  if [ -z "$OUT" ]; then
    echo "  ✗ $label — کد $CODE ولی خروجی **صفر بایت**؛ بی‌صدا مرد"; FAIL=1; return
  fi
  if ! printf '%s' "$OUT" | grep -q "بکاپ"; then
    echo "  ✗ $label — حرف زد ولی دربارهٔ بکاپ نبود:"; printf '      %s\n' "$OUT" | head -2; FAIL=1; return
  fi
  if ! printf '%s' "$OUT" | grep -q "ops/db.sh backup"; then
    echo "  ✗ $label — نگفت چه کار باید کرد"; FAIL=1; return
  fi
  echo "  ✓ $label — با پیام روشن رد شد (کد $CODE)"
}

echo "═══ تمرین بازیابی بی بکاپ ═══"

# ── ۱. پوشه اصلاً وجود ندارد — همان حالتی که بی‌صدا می‌مرد ──────────
run_drill "$TMP/no-such-dir"
expect_loud_failure "پوشهٔ بکاپ وجود ندارد"

# ── ۲. پوشه هست ولی خالی ────────────────────────────────────────────
mkdir -p "$TMP/empty"
run_drill "$TMP/empty"
expect_loud_failure "پوشهٔ بکاپ خالی است"

# ── ۳. مسیر صریح به فایلی که نیست ───────────────────────────────────
run_drill "$TMP/empty" "$TMP/nope.dump"
expect_loud_failure "مسیر صریح به فایل ناموجود"

echo
echo "═══ و با یک فایل موجود، باید از نگهبان رد شود ═══"
# ── ۴. کنترل مثبت ───────────────────────────────────────────────────
# فایل عمداً یک دامپ واقعی نیست: ادعا این است که اسکریپت از **نگهبان**
# رد می‌شود و به مرحلهٔ بازیابی می‌رسد، نه اینکه بازیابی موفق شود.
mkdir -p "$TMP/has"
printf 'not-a-real-dump' > "$TMP/has/x.dump"
run_drill "$TMP/has"
if printf '%s' "$OUT" | grep -q "پیدا نشد"; then
  echo "  ✗ با فایل موجود هم «پیدا نشد» گفت — نگهبان بیش از حد سخت‌گیر است"; FAIL=1
elif printf '%s' "$OUT" | grep -q "تمرین بازیابی"; then
  echo "  ✓ از نگهبان رد شد و به مرحلهٔ بازیابی رسید"
else
  echo "  ✗ نه رد شد نه پیام داد:"; printf '      %s\n' "$OUT" | head -3; FAIL=1
fi

echo
if [ $FAIL -eq 0 ]; then
  echo "╔══════════════════════════════════════╗"
  echo "║   نگهبان تمرین بازیابی پاس شد       ║"
  echo "╚══════════════════════════════════════╝"
else
  echo "✗✗✗ نگهبان تمرین بازیابی رد شد ✗✗✗"
  exit 1
fi
