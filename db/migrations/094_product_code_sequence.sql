-- =====================================================================
-- ۰۹۴ — کد خودکار کالای تازه: یکتا، سمت سرور، اتمیک در هم‌زمانی
-- =====================================================================
-- تا اینجا کد کالا را کاربر تایپ می‌کرد. صندوق و انبار سریع کار می‌کنند و
-- «یک کد یکتا فکر کن» یک گام کُند و خطاپذیر بود؛ کد تکراری هم به قید
-- یکتایی می‌خورد.
--
-- `catalog.next_product_code()` کد بعدی را به‌شکل `LM` + پنج رقم می‌دهد
-- (LM00001، LM00002، …؛ پس از ۹۹۹۹۹ رقم ششم می‌آید). سه قاعده:
--
-- ⚠️ **شمارنده Sequence است، نه `max(code) + 1`.** `nextval` بیرون از
--    تراکنش جلو می‌رود و هرگز یک عدد را به دو فراخوان هم‌زمان نمی‌دهد؛
--    `max + 1` در دو تراکنش هم‌زمان یک عدد می‌داد و دومی روی قید یکتایی
--    می‌شکست. عددِ تراکنشِ برگشت‌خورده می‌سوزد — کد کالا شمارهٔ سند مالی
--    نیست و پیوستگی لازم ندارد.
-- ⚠️ **کد دستی برنده است.** اگر کسی پیش‌تر همان کد را دستی (با هر
--    بزرگی/کوچکی حروف) گرفته باشد، از آن عبور می‌شود، نه اینکه درج بشکند.
-- ⚠️ **هیچ کد، SKU یا بارکد موجودی عوض نمی‌شود.** فقط شمارنده از بیشینهٔ
--    کدهای هم‌الگوی موجود جلوتر گذاشته می‌شود. بارکد داخلی (پیشوند ۲۰)
--    شمارهٔ خودش را دارد و به این شمارنده ربطی ندارد.
--
-- کد دستیِ معتبر همچنان پذیرفته می‌شود؛ این تابع فقط وقتی صدا زده می‌شود
-- که کد خالی فرستاده شود (`apps/api/src/catalog/product.ts`).
-- =====================================================================

BEGIN;

CREATE SEQUENCE catalog.product_code_seq AS bigint MINVALUE 1 START 1;

-- شمارنده پس از بیشینهٔ کدهای `LM` + رقمِ موجود. `is_called = false` روی
-- پایگاه خالی یعنی اولین `nextval` همان ۱ است.
SELECT setval('catalog.product_code_seq',
              coalesce(max(substring(upper(code) FROM '^LM([0-9]{1,15})$')::bigint), 0) + 1,
              false)
  FROM catalog.product;

CREATE FUNCTION catalog.next_product_code()
RETURNS text LANGUAGE plpgsql VOLATILE
SET search_path = pg_catalog AS $$
DECLARE
  v_code text;
  v_n    text;
BEGIN
  LOOP
    -- ⚠️ `lpad` رشتهٔ بلندتر از طول خواسته‌شده را **کوتاه** می‌کند
    --    (lpad('123456', 5) = '12345')؛ پس طول از خودِ عدد می‌آید، نه ثابت ۵.
    v_n := nextval('catalog.product_code_seq')::text;
    v_code := 'LM' || lpad(v_n, greatest(5, length(v_n)), '0');
    -- کد دستیِ هم‌نام (حتی با حروف کوچک) یعنی این عدد گرفته شده است.
    EXIT WHEN NOT EXISTS (SELECT 1 FROM catalog.product p WHERE upper(p.code) = v_code);
  END LOOP;
  RETURN v_code;
END
$$;
COMMENT ON FUNCTION catalog.next_product_code IS
  'کد خودکار کالای تازه (LM + رقم) از catalog.product_code_seq؛ اتمیک در هم‌زمانی و از کدهای دستیِ موجود عبور می‌کند.';

COMMIT;
