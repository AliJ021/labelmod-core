-- =====================================================================
-- ۰۲۴ — تنظیمی که دروغ می‌گفت
-- =====================================================================
-- `ledger.sale_posting` از اول دو گزینه داشت: `per_shift` و
-- `per_invoice`. در صفحه تنظیمات دیده می‌شد، عوض هم می‌شد، و در
-- `audit_log` هم می‌نشست.
--
-- **ولی هیچ کدی نمی‌خواندش.** جست‌وجو شد: نه در مهاجرت‌ها، نه در
-- `apps/api`. یعنی مالک می‌توانست روی «یک سند برای هر فاکتور»
-- بگذارد و سیستم بی‌سروصدا همان تجمیعی را ادامه دهد.
--
-- تنظیمی که کار نکند از نبودنش بدتر است: کسی رویش حساب می‌کند.
--
-- ── چرا گزینه حذف می‌شود و پیاده نمی‌شود ────────────────────────────
--
-- چون `per_invoice` کدِ نانوشته نیست، یک **تصمیم معماری** است که
-- ADR-003 عمداً جور دیگری گرفته:
--
--   `ledger.posting_batch` دو ستون **تکی** دارد: `sale_entry_id` و
--   `cogs_entry_id`. کل Idempotency روی همین‌هاست — `post_batch` وقتی
--   دوباره صدا زده شود، همان دو شناسه را برمی‌گرداند به‌جای اینکه سند
--   دوم بزند. با «هر فاکتور»، N سند ساخته می‌شود و این دو ستون
--   نمی‌توانند نگهشان دارند.
--
-- پس پیاده‌سازی‌اش یعنی: یک جدول پیوند تازه (دوره ← اسناد)، بازنویسی
-- `post_batch`، و بازنگری در `unposted_revenue` و
-- `GET /posting-batches/*`. این تغییر ADR می‌خواهد، نه یک مهاجرت.
--
-- تا آن تصمیم گرفته نشود، **گزینه‌ای که کار نمی‌کند نباید در صفحه
-- باشد.**
-- =====================================================================

BEGIN;

UPDATE platform.setting
   SET options = '[{"value":"per_shift","label":"یک سند برای هر شیفت (تجمیعی)"}]'::jsonb,
       value   = '"per_shift"'::jsonb,
       description = 'تجمیع سند فروش. فعلاً فقط تجمیعی پیاده شده است.',
       help = 'تجمیعی: در پایان هر شیفت یک سند برای کل فروش آن شیفت زده می‌شود و دفتر خلوت می‌ماند — برای فروشگاه تک‌شعبه معمولاً همین درست است. ⚠️ گزینه «یک سند برای هر فاکتور» موقتاً برداشته شد چون پیاده نشده بود و انتخابش هیچ اثری نداشت. پیاده‌سازی‌اش یک تصمیم معماری است: Idempotency دوره ثبت روی دو ستون تکی sale_entry_id و cogs_entry_id بنا شده و با یک سند به‌ازای هر فاکتور، آن دو ستون کافی نیستند.'
 WHERE key = 'ledger.sale_posting';

COMMIT;
