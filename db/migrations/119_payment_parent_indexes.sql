-- =====================================================================
-- ۱۱۹ — ایندکس پرداخت روی فاکتور و مرجوعی
-- =====================================================================
-- یافتهٔ ممیزی LM-05 (۲۰۲۶/۱۱/۱۲). `treasury.payment` پنج ایندکس داشت و
-- هیچ‌کدام روی `invoice_id` یا `return_id` نبود، در حالی که «پرداخت‌های
-- این فاکتور» پرتکرارترین خواندنِ این جدول است: `sales.finalize_invoice`،
-- `sales.post_return`، زیرکوئری همبستهٔ `sales.post_batch` (به‌ازای هر
-- فاکتورِ دوره)، صفحهٔ عمومی فاکتور و چند گزارش. اندازه‌گیری ممیزی با
-- ۱۰٬۰۰۰ پرداخت: `Seq Scan … Rows Removed by Filter: 9999` برای هر خواندن.
-- یعنی زمان هر فروش با شمار **همهٔ** پرداخت‌های تاریخ رشد می‌کرد.
--
-- ایندکس‌ها جزئی‌اند: قید `payment_has_one_parent` می‌گوید هر پرداخت
-- دقیقاً یک والد دارد، پس در هر کدام نیمی از سطرها تهی‌اند و جایی نمی‌گیرند.
--
-- ⚠️ `CREATE INDEX` بی `CONCURRENTLY` در زمان ساخت **نوشتن** روی جدول را
--    می‌بندد (خواندن باز است). `CONCURRENTLY` داخل تراکنش ممکن نیست و قاعدهٔ
--    این مخزن «هر مهاجرت در یک تراکنش» است. روی نصبی که هنوز فروش واقعی
--    ندارد لحظه‌ای است؛ روی جدول پرسطر، پنجرهٔ نگهداری لازم است — مثل
--    ایندکس ۰۷۹ روی `sales.invoice`.
-- ⚠️ `lock_timeout` صریح است تا مهاجرت پشت یک تراکنش طولانی صف نکشد و
--    در همان مدت هر فروش تازه‌ای را پشت خودش نگه ندارد.
--
-- آزمون: `db/test/payment-indexes.sql` — وجود هر دو ایندکس از کاتالوگ و
-- اینکه برنامه‌ریز برای «پرداخت‌های یک فاکتور» واقعاً از آن استفاده می‌کند.
-- =====================================================================

BEGIN;

SET LOCAL lock_timeout = '5s';

CREATE INDEX payment_invoice_id_idx ON treasury.payment (invoice_id)
  WHERE invoice_id IS NOT NULL;

CREATE INDEX payment_return_id_idx ON treasury.payment (return_id)
  WHERE return_id IS NOT NULL;

COMMIT;
