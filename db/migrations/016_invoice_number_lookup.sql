-- =====================================================================
-- ۰۱۶ — یافتن فاکتور از روی شماره رسید
-- =====================================================================
-- مرجوعی از روی رسیدِ دست مشتری شروع می‌شود، و روی آن رسید یک
-- **شماره** چاپ شده — «F-1405-000123» — نه یک UUID. تا امروز هیچ
-- مسیری از شماره به فاکتور نمی‌رسید، پس صفحه مرجوعی ساختنی نبود.
--
-- ستون `number` نه ایندکس داشت و نه یکتایی. هر دو عمدی نبوده‌اند —
-- فقط تا امروز کسی از این راه سراغ فاکتور نرفته بود.
--
-- ── چرا ایندکس روی (branch_id, number) و نه فقط number ────────────
--
-- شماره **در سطح شعبه** یکتاست، نه در کل سیستم:
-- `platform.next_document_no()` شمارنده را به (شعبه، نوع سند، سال
-- مالی) می‌بندد. اگر فردا شعبه دومی با همان پیشوند 'F-1405-' ساخته
-- شود، دو فاکتور با شماره یکسان در دو شعبه وجود خواهند داشت — و آن
-- یک تعارض نیست، چون رسید هر شعبه مال خودش است.
--
-- پس جست‌وجو هم همیشه باید شعبه‌دار باشد. ایندکس همان ترتیب را
-- می‌گیرد تا کوئری واقعی از آن استفاده کند.
--
-- ── چرا Partial ───────────────────────────────────────────────────
--
-- فاکتور پیش‌نویس `number` ندارد — شماره فقط در لحظه Commit تخصیص
-- می‌یابد. پیش‌نویس‌ها پرگردش‌ترین سطرهای این جدول‌اند (هر سبد رهاشده
-- یکی) و نگه‌داشتنشان در ایندکس، هزینه‌ای است بدون فایده.
--
-- ⚠️ این مهاجرت **یکتایی اضافه نمی‌کند.** وسوسه‌اش بود، ولی
-- `UNIQUE (branch_id, number)` روی داده‌ای که هنوز وارد نشده یک ادعای
-- نسنجیده است: تا وقتی مهاجرت داده از سیستم فعلی انجام نشده، معلوم
-- نیست شماره‌های تاریخی همین قاعده را داشته‌اند یا نه. اگر داشتند،
-- افزودنش بعداً یک مهاجرت یک‌خطی است.
-- =====================================================================

BEGIN;

CREATE INDEX IF NOT EXISTS invoice_branch_number_idx
  ON sales.invoice (branch_id, number)
  WHERE number IS NOT NULL;

COMMENT ON INDEX sales.invoice_branch_number_idx IS
  'یافتن فاکتور از روی شماره رسید، در دامنه شعبه. شماره در سطح شعبه یکتاست، نه سراسری.';

COMMIT;
