-- =====================================================================
-- ۰۱۱ — مهلت مرجوعی به ساعت، نه روز
-- =====================================================================
-- مالک گفت: «مهلت مرجوعی ۴۸ ساعت باشد، اما این را هم بشود داخل تنظیمات
-- ساده تغییر داد.»
--
-- ## چرا «۲ روز» جواب نمی‌داد
--
-- محاسبه فعلی روز صحیح می‌گیرد و بعد مقایسه می‌کند:
--
--   floor(ثانیه / 86400) > return.window_days
--
-- با `window_days = 2`، فاکتوری که ۷۱ ساعت پیش نهایی شده `days = 2`
-- می‌دهد و «داخل مهلت» شمرده می‌شود. یعنی مهلت واقعی ۷۲ ساعت است، نه
-- ۴۸. برای مشتری‌ای که ساعت ۹ صبح خرید کرده و سه روز بعد ساعت ۸ صبح
-- برمی‌گردد، این تفاوت یک «بله» در برابر یک «نه» است.
--
-- گرد کردن روز اصلاً نمی‌تواند ۴۸ ساعت را بیان کند. پس واحد عوض شد.
--
-- ## یک کلید، نه دو تا
--
-- `return.window_days` **حذف** می‌شود، نه اینکه کنار کلید تازه بماند.
-- دو تنظیم برای یک قاعده یعنی همان «دو نسخه از یک قاعده» که دیر یا
-- زود از هم جدا می‌شوند — و آن که کدی نمی‌خواندش، همان است که
-- حسابدار عوضش می‌کند و تعجب می‌کند چرا اثری ندارد.
--
-- مقدار موجود **تبدیل** می‌شود، نه دور انداخته: اگر مالک روی نصب
-- فعلی ۱۴ روز گذاشته باشد، ۳۳۶ ساعت می‌شود — نه ۴۸.
-- =====================================================================

BEGIN;

-- تبدیل مقدار موجود. روی دیتابیس تازه این INSERT هیچ سطری نمی‌سازد
-- (کلید قدیمی هنوز وجود ندارد) و `db/seed/030_settings.sql` بعداً
-- پیش‌فرض ۴۸ را می‌گذارد.
--
-- فراداده اینجا حداقلی است؛ seed کاملش می‌کند. ولی `is_editable` از
-- همین‌جا روشن است تا اگر کسی فقط مهاجرت را اجرا کرد، تنظیم قفل
-- نماند.
INSERT INTO platform.setting
  (key, value, description, requires_approval,
   kind, label, group_key, min_value, max_value, unit, sort_order,
   permission, is_editable)
SELECT
  'return.window_hours',
  to_jsonb((s.value #>> '{}')::int * 24),
  'مهلت مرجوعی بدون تأیید مدیر، به ساعت.', true,
  'int', 'مهلت مرجوعی بدون تأیید مدیر', 'returns', 0, 8760, 'ساعت', 10,
  'settings.security', true
  FROM platform.setting s
 WHERE s.key = 'return.window_days'
ON CONFLICT (key) DO NOTHING;

DELETE FROM platform.setting WHERE key = 'return.window_days';

COMMIT;
