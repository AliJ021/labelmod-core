-- تصمیم مالک (۲۰۲۶/۱۱/۰۹): در هر جایی که کاربر می‌بیند، «Core» (نام فنی
-- درونی) «مرکز» نوشته می‌شود. رابط و پیام‌های سرور در کد عوض شدند؛ این تنها
-- متنی است که در دیتابیس نشسته و صفحهٔ تنظیمات نشانش می‌دهد.
--
-- فقط **توضیح** عوض می‌شود، نه مقدار، نوع یا مجوز. و فقط اگر همان متن
-- اصلی Seed مانده باشد: توضیحی که کسی عوض کرده دست نمی‌خورد. تکرار
-- مهاجرت هم اثری ندارد.
-- =====================================================================

